// ============================================================================
// Generator: scans every string literal in the vendored calc engine
// (src/lib/**/*.ts) and emits src/upgrade/lib/itemEffectTags.ts — the subset
// of those literals that appear (case-sensitively) inside at least one item
// name in cdn/json/equipment.json.
//
// Why: the calc engine applies item-specific effects by NAME — exact checks
// (`wearing('Salve amulet(ei)')`), substring checks (`name.includes('Virtus')`),
// suffix checks (`endsWith('halberd')`).
// src/upgrade/lib/itemDominance.ts gives each item an effect signature: for
// every literal its name contains, whether the name equals / starts with /
// ends with it. Two items with identical signatures get the same outcome from
// every name check whichever operator the calc uses, so the dominance rules
// only compare effect items with identically-signed ones. Any literal is
// kept, however short or generic — an extra literal can only split items
// into more signatures (fewer comparisons), never merge them.
//
// Re-run after every `npm run sync-upstream`: `npx jest ItemEffectTagsGen`.
// ============================================================================

import fs from 'fs';
import path from 'path';
import { describe, test } from '@jest/globals';
import { EquipmentPiece } from '@/types/Player';
import eqJson from '../../../cdn/json/equipment.json';

const equipment = eqJson as EquipmentPiece[];

// =====
// Literals shorter than this are skipped: 1-2 character strings in the calc
// are operators / separators, never item names.
// =====
const MIN_LITERAL = 3;

function listCalcSources(dir: string): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listCalcSources(full));
    else if (entry.name.endsWith('.ts')) out.push(full);
  }
  return out.sort();
}

describe('Generate item effect tags', () => {
  test('emit src/upgrade/lib/itemEffectTags.ts', () => {
    const libDir = path.resolve(__dirname, '../../lib');
    const files = listCalcSources(libDir);

    // ----- Collect every single/double-quoted string literal -----
    const literals = new Set<string>();
    const literalRe = new RegExp(`'([^'\\\\\\n]{${MIN_LITERAL},})'|"([^"\\\\\\n]{${MIN_LITERAL},})"`, 'g');
    for (const f of files) {
      const src = fs.readFileSync(f, 'utf8');
      for (const m of src.matchAll(literalRe)) literals.add(m[1] ?? m[2]);
    }

    // ----- Keep only literals that appear inside at least one item name -----
    const names = [...new Set(equipment.map((e) => e.name))];
    const matching = [...literals].filter((l) => names.some((n) => n.includes(l)));
    matching.sort((a, b) => a.localeCompare(b));

    const rel = files.map((f) => path.relative(path.resolve(__dirname, '../../..'), f).replace(/\\/g, '/'));
    const ts = [
      '// AUTO-GENERATED by src/upgrade/tests/ItemEffectTagsGen.test.ts -- do not edit by hand.',
      '// Re-run after every `npm run sync-upstream`: `npx jest ItemEffectTagsGen`.',
      '//',
      '// String literals from the vendored calc engine that appear inside at',
      '// least one equipment.json item name. See the generator header for why.',
      `// Scanned ${rel.length} files under src/lib/.`,
      '',
      'export const CALC_ITEM_NAME_LITERALS: readonly string[] = [',
      ...matching.map((l) => `  ${JSON.stringify(l)},`),
      '];',
      '',
    ].join('\n');

    const outPath = path.resolve(__dirname, '../lib/itemEffectTags.ts');
    fs.writeFileSync(outPath, ts, 'utf8');
    /* eslint-disable no-console */
    console.log(`\nWrote ${outPath} -- ${matching.length} literals (of ${literals.size}) from ${files.length} files`);
    /* eslint-enable no-console */
  });
});
